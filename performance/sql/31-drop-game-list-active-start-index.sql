/*
 * ============================================================
 * 기본 경기 목록 조회 복합 인덱스 롤백
 * ============================================================
 *
 * 대상 인덱스:
 * - idx_game_list_active_start
 *
 * 주의:
 * - 성능 개선을 되돌려야 할 때만 실행한다.
 * - GameEntity의 @Table 인덱스 정의도 함께 제거해야 한다.
 * - ddl-auto=update 환경에서는 애플리케이션 재시작 시
 *   엔티티 정의에 따라 인덱스가 다시 생성될 수 있다.
 * ============================================================
 */

USE basketball;


/* ============================================================
 * 1. 대상 환경 확인
 * ============================================================
 */

SELECT
    DATABASE() AS target_database,
    VERSION() AS mysql_version,
    NOW(6) AS rollback_started_at;


/* ============================================================
 * 2. 삭제 대상 인덱스 확인
 * ============================================================
 *
 * 복합 인덱스의 두 컬럼이 조회되어야 한다.
 * ============================================================
 */

SELECT
    index_name,
    seq_in_index,
    column_name
FROM information_schema.statistics
WHERE table_schema = DATABASE()
  AND table_name = 'game_entity'
  AND index_name = 'idx_game_list_active_start'
ORDER BY seq_in_index;


/* ============================================================
 * 3. 복합 인덱스 제거
 * ============================================================
 */

DROP INDEX idx_game_list_active_start
    ON game_entity;


/* ============================================================
 * 4. 옵티마이저 통계 갱신
 * ============================================================
 */

ANALYZE TABLE game_entity;


/* ============================================================
 * 5. 제거 결과 확인
 * ============================================================
 *
 * 결과가 0이어야 롤백이 완료된 것이다.
 * ============================================================
 */

SELECT
    COUNT(*) AS remaining_index_column_count
FROM information_schema.statistics
WHERE table_schema = DATABASE()
  AND table_name = 'game_entity'
  AND index_name = 'idx_game_list_active_start';